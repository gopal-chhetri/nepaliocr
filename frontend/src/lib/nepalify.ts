/** Convert a latin/Nepali-Unicode string into Devanagari using the given layout. */
export function nepalify(text: string, layout: NepaliLayout = 'romanized'): string {
  const map = KEYMAPS[layout]
  return Array.from(String(text), (c) => map[c] ?? c).join('')
}